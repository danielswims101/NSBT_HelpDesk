export function angelaNote(lines: { code: string; status: WorksheetStatus; note: string }[]): string {
  const pulled = lines.filter((l) => l.status === "sent" || l.status === "pulled");
  const failed = lines.filter((l) => l.status === "failed");
  const left = lines.filter((l) => l.status === "todo");
  const today = new Date().toISOString().slice(0, 10);
  return [
    `Institutional lead — daily worksheet note ${today}`,
    `From: Office of Student Records and Accounts`,
    `Copy Angela White on 76a and any admissions reason.`,
    "",
    `Pulled / sent: ${pulled.map((l) => l.code).join(", ") || "none yet"}`,
    `CHECK failed (not sent): ${failed.map((l) => `${l.code}${l.note ? ` (${l.note})` : ""}`).join("; ") || "none"}`,
    `Still open: ${left.map((l) => l.code).join(", ") || "none"}`,
    "",
    "I am not opening a Populi ticket per line. Weekend pulls first. One screen-share for what needs Support.",
    "I will not send a one-year file on an all-years or every-cohort card.",
  ].join("\n");
}
